#!/bin/bash
# Скрипт ручного сброса системы BlackBox
# Использование: ./scripts/manual-reset.sh
# ПРЕДУПРЕЖДЕНИЕ: ТОЛЬКО ДЛЯ РАЗРАБОТКИ!

echo "=== Сброс системы разработки ==="
echo "Этот скрипт сбрасывает ВСЕ данные в системе."
echo "Использовать только для разработки!"
echo ""

# Загрузка переменных из .env файла
if [ -f "../.env" ]; then
    source "../.env"
elif [ -f ".env" ]; then
    source ".env"
else
    echo "❌ Файл .env не найден"
    exit 1
fi

# Проверка переменной окружения
if [ "$DEV_FULL_RESET" != "true" ]; then
    echo "❌ ПРОВЕРКА БЕЗОПАСНОСТИ НЕ ПРОЙДЕНА"
    echo ""
    echo "Текущее значение DEV_FULL_RESET: $DEV_FULL_RESET"
    echo ""
    echo "Чтобы включить этот сброс, установите в файле .env:"
    echo "DEV_FULL_RESET=true"
    echo ""
    echo "Это предотвращает случайную потерю данных в продакшн."
    exit 1
fi

echo "✅ ПРОВЕРКА БЕЗОПАСНОСТИ ПРОЙДЕНА: DEV_FULL_RESET=true"
echo ""
read -p "Вы уверены, что хотите сбросить ВСЕ данные разработки? (y/N): " -n 1 -r
echo
if [[ ! $REPLY =~ ^[Yy]$ ]]; then
    echo "Сброс отменен."
    exit 1
fi

echo ""
echo "🔄 Запуск сброса системы разработки..."

# Остановка и удаление всех контейнеров
echo "⏹️  Остановка всех контейнеров..."
docker-compose down

# Удаление volumes (это удалит все данные)
echo "🗑️  Удаление Docker volumes и всех данных..."
docker-compose down -v

# Перезапуск с чистыми контейнерами
echo "🚀 Запуск чистых контейнеров..."
docker-compose up -d --build

# Ожидание готовности сервисов
echo "⏳ Ожидание готовности сервисов..."
sleep 30

# Проверка запущенных сервисов
echo "📊 Проверка статуса сервисов..."
docker-compose ps

echo ""
echo "✅ Сброс системы разработки завершен"
echo ""
echo "Система полностью сброшена:"
echo "- База данных: Очищена"
echo "- MinIO: Очищен" 
echo "- Локальный кеш: Очищен"
echo "- Все данные разработки: Удалены"
echo ""
echo "💡 Для предотвращения будущих случайных сбросов:"
echo "   Установите DEV_FULL_RESET=false в .env"
echo ""
echo "🌐 Посетите http://localhost:3000 для просмотра чистой системы."